#!/usr/bin/env python3
"""Start only an owned standalone MediaMTX receiver and inspect its sockets.

Linux /proc listener evidence, no OBS lifecycle, no media source or credentials.
The parent owns all OBS processes. Old runtime PASS reports are not rewritten.
"""
import argparse
import datetime
import hashlib
import json
from pathlib import Path
import socket
import subprocess
import time


def sockets(pid):
    inodes=set()
    for fd in (Path('/proc')/str(pid)/'fd').iterdir():
        try:
            target=fd.readlink().as_posix()
            if target.startswith('socket:['):inodes.add(target[8:-1])
        except FileNotFoundError:pass
    found=[]
    for proto in ['tcp','tcp6','udp','udp6']:
        for line in (Path('/proc/net')/proto).read_text().splitlines()[1:]:
            fields=line.split()
            if fields[9] not in inodes:continue
            address,port=fields[1].split(':')
            if proto.endswith('6'):
                raw=bytes.fromhex(address)
                raw=b''.join(raw[i:i+4][::-1] for i in range(0,16,4))
                host=socket.inet_ntop(socket.AF_INET6,raw)
            else:host=socket.inet_ntoa(bytes.fromhex(address)[::-1])
            found.append({'protocol':proto,'address':host,'port':int(port,16),'state':fields[3]})
    return found


def main():
    p=argparse.ArgumentParser(description=__doc__);p.add_argument('root',type=Path);p.add_argument('--server',type=Path,required=True);a=p.parse_args()
    a.root.mkdir(parents=True,exist_ok=True,mode=0o700);report=a.root/'listener-validation.json'
    if report.exists():raise FileExistsError(report)
    with socket.socket() as allocated:allocated.bind(('127.0.0.1',0));port=allocated.getsockname()[1]
    yaml=a.root/'receiver.yml'
    assert not yaml.exists(),yaml
    yaml.write_text(f'''logLevel: info
rtsp: false
rtmp: true
rtmpAddress: 127.0.0.1:{port}
hls: false
webrtc: false
srt: false
moq: false
playback: false
api: false
metrics: false
pprof: false
paths:
  all_others:
    source: publisher
''')
    expected=[{'protocol':'tcp','address':'127.0.0.1','port':port,'state':'0A'}]
    with (a.root/'receiver.log').open('wb') as log:
        child=subprocess.Popen([str(a.server.resolve()),str(yaml.resolve())],cwd=a.root.resolve(),stdout=log,stderr=subprocess.STDOUT)
        try:
            deadline=time.monotonic()+5;observed=[]
            while time.monotonic()<deadline:
                assert child.poll() is None,('receiver exited early',child.returncode)
                observed=sockets(child.pid)
                if observed:break
                time.sleep(.05)
            assert observed==expected,(observed,expected)
            time.sleep(.5)
            stable=sockets(child.pid)
            assert stable==expected,(stable,expected)
            assert not (a.root/'auto.key').exists() and not (a.root/'auto.crt').exists(),'unexpected autogenerated TLS artifacts'
            result={'passed':True,'utc':datetime.datetime.now(datetime.timezone.utc).isoformat(),'server':str(a.server.resolve()),
                    'server_sha256':hashlib.sha256(a.server.read_bytes()).hexdigest(),'yaml':str(yaml.resolve()),
                    'yaml_sha256':hashlib.sha256(yaml.read_bytes()).hexdigest(),'working_directory':str(a.root.resolve()),
                    'network_sockets':stable,'moq_disabled':True,'playback_disabled':True,'new_tls_artifacts':False,
                    'scope':'Owned standalone receiver TCP/UDP sockets via Linux /proc; no OBS, no media, no public endpoints; historical active-1 MoQ-default issue is preserved separately'}
        finally:
            child.terminate()
            try:child.wait(timeout=3)
            except subprocess.TimeoutExpired:child.kill();child.wait(timeout=3)
    result['process_terminated']=child.poll() is not None
    with report.open('x') as out:json.dump(result,out,indent=2);out.write('\n')
    print(json.dumps({'passed':True,'network_sockets':result['network_sockets'],'report':str(report)}))


if __name__=='__main__':main()
